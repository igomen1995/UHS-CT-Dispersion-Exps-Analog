%% CT Concentration Analysis and Transport Metrics Extraction
%
% This script extracts quantitative transport information from processed
% concentration images generated from CT experiments.
%
% Concentration images previously stored in HDF5 format are analyzed to
% compute spatial concentration profiles, breakthrough curves, mixing-zone
% characteristics, and concentration-front velocities.
%
% The resulting variables are consolidated into a structured MATLAB object
% and saved for downstream visualization and comparative analysis.
%
% Workflow
% --------
% 1. Import experiment metadata and configuration.
% 2. Load scanner metadata (.pca, .pcj, .pcp).
% 3. Read concentration images from HDF5 storage.
% 4. Compute concentration statistics for each image:
%       - Axial concentration profile
%       - Vertical concentration profile
%       - Concentration histogram
%       - Injected pore volumes
%       - Dimensionless time
% 5. Determine concentration-front locations:
%       - C = 0.1 front
%       - C = 0.9 front
%       - Front width
% 6. Construct breakthrough curves.
% 7. Estimate front propagation velocity.
% 8. Generate contour-based front maps.
% 9. Compute apparent velocity fields from contour displacement.
% 10. Save all processed variables into a MATLAB structure.
%
% Inputs
% ------
% inputCTExpConfig.xlsx
%     Repository configuration file.
%
% Processed HDF5 files
%     Generated by the image processing workflow and containing:
%
%         /exp/run_xx/conc
%
%     where each dataset is a stack of concentration images.
%
% Scanner Metadata
% ----------------
% .pca
%     Scanner and reconstruction parameters.
%
% .pcp
%     Acquisition timestamps and scan information.
%
% .pcj
%     Reconstruction metadata.
%
% Outputs
% -------
% One MAT file per experiment:
%
%     <ExperimentKey>.mat
%
% containing:
%
%     CFparams
%     BTlinesBefore
%     BTcore
%     concVarsAll
%     refInit
%     refFinal
%     exp
%
% Key Quantities Calculated
% -------------------------
%
% C1Profile
%     Cross-sectionally averaged concentration as a function of core
%     length:
%
%         C1(z)
%
% C1Axial
%     Laterally averaged concentration as a function of horizontal
%     position:
%
%         C1(x)
%
% BTcore
%     Breakthrough curve based on outlet concentration.
%
% BTlinesBefore
%     Breakthrough curve based on inlet concentration.
%
% zFront10
%     Mean position of the C = 0.1 concentration contour.
%
% zFront90
%     Mean position of the C = 0.9 concentration contour.
%
% zWidth
%     Mixing-zone width:
%
%         zWidth = zFront10 - zFront90
%
% tDcorr
%     Corrected dimensionless time based on measured front velocity.
%
% Velocity Field Analysis
% -----------------------
%
% Concentration contours from:
%
%     C = 0.1, 0.2, ..., 0.9
%
% are tracked between consecutive images.
%
% Displacements are converted into:
%
%     uz_field   Vertical front velocity [cm/s]
%
% providing a simple estimate of concentration-front motion throughout
% the experiment.
%
% Dependencies
% ------------
%
%     import_inputCTExp
%     importPCA
%     importPCP
%     importPCJ
%
% MATLAB Functions
% ----------------
%
%     h5read
%     h5info
%     histcounts
%     gradient
%
% Notes
% -----
%
% Front positions are estimated using concentration bands:
%
%     0.05 ≤ C ≤ 0.15   -> C = 0.1 front
%     0.85 ≤ C ≤ 0.95   -> C = 0.9 front
%
% Concentration contour maps are generated using concentration intervals:
%
%     C = 0.1 : 0.1 : 0.9
%
% These contour maps are used solely for front tracking and velocity-field
% estimation.

%% IMPORT input

Root = CT_setupPaths;

% Introduce name of input and desired output folder name

inputFileConfigName = 'inputCTExpConfig.xlsx';
inputFileConfig = readtable(inputFileConfigName);


%% Extract data from images

for i = 1:height(inputFileConfig)

    filenameExp = inputFileConfig.inputFileName{i};

    pathImportAll = inputFileConfig.importPath{i}; % Path for OUTPUT
    pathExportAll = inputFileConfig.exportPath{i}; % Path for OUTPUT
    mkdir(pathExportAll); % Create directory for output

    filedataExp = import_inputCTExp(filenameExp); % import input to a local variable

    % MFM analog (CT) data for this experiment — source of D
    pathImport_MFM_CT = regexprep(inputFileConfig.MFM_BTC_CT_Path{i}, '^(\.\./)+', '');
    MFM_CT_name = inputFileConfig.MFM_BTC_CT_Key{i};
    MFM_CT_file = fullfile(Root, pathImport_MFM_CT, 'expProcFullData.mat');

    if ~isfile(MFM_CT_file)
        error('MFM results file not found: %s', MFM_CT_file);
    end
    MFM_CT_Data = load(MFM_CT_file);
    expProcFullData_MFM_CT = MFM_CT_Data.expProcFullData.(MFM_CT_name);
    D = expProcFullData_MFM_CT.exp_params.D12_cm2min;

    % Capture init ref data folder
    refInitFolderContent = dir(filedataExp.path+filedataExp.CT_data_ref_init); % Xe
    refInitFolderContent = refInitFolderContent([refInitFolderContent.isdir] & ~startsWith({refInitFolderContent.name},'.'));
    refInitFolderName = refInitFolderContent.name;
    
    % Capture final ref data folder
    refFinalFolderContent = dir(filedataExp.path+filedataExp.CT_data_ref_final); % He
    refFinalFolderContent = refFinalFolderContent([refFinalFolderContent.isdir] & ~startsWith({refFinalFolderContent.name},'.'));
    refFinalFolderName = refFinalFolderContent.name;
    
    % Capture exp data folder
    expFolderContent = dir(filedataExp.path+filedataExp.CT_data_exp); % exp
    expFolderContent = expFolderContent([expFolderContent.isdir] & ~startsWith({expFolderContent.name},'.'));
    expFolderName = {expFolderContent.name}';
    expFolderPath = {expFolderContent.folder};
    
    % BT extract
    concBTlinesBefore = table(); 
    concBTcore = table();
    rhoNormBTlinesBefore = table(); 
    rhoNormBTcore = table();
    expCTData = struct();

    % Image
    HDF5filename = fullfile(pathExportAll, filedataExp.Key + ".h5");

    % CF params
    expCTData.(filedataExp.Key).CFparams = filedataExp;

    % CT init ref
    refInitFolderPathCT = fullfile(refInitFolderContent.folder, refInitFolderName);
        % pca
        refInitpcaFiles = dir(fullfile(refInitFolderPathCT, '*.pca'));
        expCTData.(filedataExp.Key).refInit.pca = importPCA(refInitpcaFiles);
        % pcj 
        refInitpcjFiles = dir(fullfile(refInitFolderPathCT, '*.pcj'));
        expCTData.(filedataExp.Key).refInit.pcj = importPCJ(refInitpcjFiles);
        % pcp
        refInitpcpFiles = dir(fullfile(refInitFolderPathCT, '*.pcp'));
        expCTData.(filedataExp.Key).refInit.pcp = importPCP(refInitpcpFiles);
        % CTimages folder 
        
    nn_refInit = height(expCTData.(filedataExp.Key).refInit.pcp);

    % CT final ref
    refFinalFolderPathCT = fullfile(refFinalFolderContent.folder, refFinalFolderName);
        % pca
        refFinalpcaFiles = dir(fullfile(refFinalFolderPathCT, '*.pca'));
        expCTData.(filedataExp.Key).refFinal.pca = importPCA(refFinalpcaFiles);
        % pcj 
        refFinalpcjFiles = dir(fullfile(refFinalFolderPathCT, '*.pcj'));
        expCTData.(filedataExp.Key).refFinal.pcj = importPCJ(refFinalpcjFiles);
        % pcp
        refFinalpcpFiles = dir(fullfile(refFinalFolderPathCT, '*.pcp'));
        expCTData.(filedataExp.Key).refFinal.pcp = importPCP(refFinalpcpFiles);

    % BT varsAll
    rhoNormVarsAll = table();
    concVarsAll = table();

    % u interstitial theoretical
    uint = filedataExp.Q/(filedataExp.phi*pi*((filedataExp.D*2.54/2)^2));

    % interpolant for composition form array 0 to 1 (binary mixture)
    interpFcn = buildInterpolant(filedataExp.Fluid1, ...
        filedataExp.Fluid2, filedataExp.T, filedataExp.P);



    for j = 1:length(expFolderName)
        expFolderPathCT = fullfile(expFolderPath{j}, expFolderName{j});
        run_name = "run_" + sprintf('%02d', j);
            % pca
            exppcaFiles = dir(fullfile(expFolderPathCT, '*.pca'));
            expCTData.(filedataExp.Key).exp.(run_name).pca = importPCA(exppcaFiles);
            % pcj 
            exppcjFiles = dir(fullfile(expFolderPathCT, '*.pcj'));
            expCTData.(filedataExp.Key).exp.(run_name).pcj = importPCJ(exppcjFiles);
            % pcp
            exppcpFiles = dir(fullfile(expFolderPathCT, '*.pcp'));
            expCTData.(filedataExp.Key).exp.(run_name).pcp = importPCP(exppcpFiles);

        nn_exp = height(expCTData.(filedataExp.Key).exp.(run_name).pcp); % per run

        HDF5dataPath = ['/exp/' char(run_name) '/conc'];  % structured path
        info = h5info(HDF5filename, HDF5dataPath);
        dims = info.Dataspace.Size;
        nx = dims(1);
        ny = dims(2);
        nz = dims(3);
        
        for k = 1:nn_exp
            % Concentration profiles and histograms of normalized images
            imgNr = expCTData.(filedataExp.Key).exp.(run_name).pcp.ImgNr(k);
            rotPos = expCTData.(filedataExp.Key).exp.(run_name).pcp.RotPos(k);
            timeStamp = expCTData.(filedataExp.Key).exp.(run_name).pcp.Time(k);
            timeStart = filedataExp.st;
            timeElapsed = timeStamp - timeStart;
            secondsElapsed = seconds(timeElapsed);
            volInjected = secondsElapsed*filedataExp.Q/60;
            tDtotal = volInjected/filedataExp.Vtotal;
            rhoNormImage = h5read(HDF5filename, HDF5dataPath, [1 1 k], [nx ny 1]);
            concImage = interpFcn(rhoNormImage);

            resXmm = expCTData.(filedataExp.Key).exp.(run_name).pca.Geometry.VoxelSizeX;
            resYmm = expCTData.(filedataExp.Key).exp.(run_name).pca.Geometry.VoxelSizeY;

            rhoNormVars_k = populate_CTframeVars(rhoNormImage, resXmm, resYmm, ...
                imgNr, rotPos, timeStamp, timeElapsed, secondsElapsed, volInjected, tDtotal,D);
            expCTData.(filedataExp.Key).exp.(run_name).rhoNormVars(k) = rhoNormVars_k;
            
            concVars_k = populate_CTframeVars(concImage, resXmm, resYmm, ...
                imgNr, rotPos, timeStamp, timeElapsed, secondsElapsed, volInjected, tDtotal,D);
            expCTData.(filedataExp.Key).exp.(run_name).concVars(k) = concVars_k;

            % BT rhoNorm case
            rhoNormBTlinesBefore_temp = table(timeStamp, timeElapsed, secondsElapsed, volInjected, tDtotal, rhoNormVars_k.CD1inlet, ...
                'VariableNames',{'timeStamp','timeElapsed','secondsElapsed','volInjected','tDtotal','CD1'});
            rhoNormBTcore_temp = table(timeStamp, timeElapsed, secondsElapsed, volInjected, tDtotal, rhoNormVars_k.CD1, ...
                rhoNormVars_k.zFront10, rhoNormVars_k.zFront50, rhoNormVars_k.zFront90, rhoNormVars_k.zWidth, rhoNormVars_k.zWidthDiff, ...
                'VariableNames',{'timeStamp','timeElapsed','secondsElapsed','volInjected','tDtotal','CD1','zFront10','zFront50','zFront90','zWidth','zWidthDiff'});
            rhoNormBTlinesBefore = [rhoNormBTlinesBefore; rhoNormBTlinesBefore_temp];
            rhoNormBTcore = [rhoNormBTcore; rhoNormBTcore_temp];

            % BT conc case
            concBTlinesBefore_temp = table(timeStamp, timeElapsed, secondsElapsed, volInjected, tDtotal, concVars_k.CD1inlet, ...
                'VariableNames',{'timeStamp','timeElapsed','secondsElapsed','volInjected','tDtotal','CD1'});
            concBTcore_temp = table(timeStamp, timeElapsed, secondsElapsed, volInjected, tDtotal, concVars_k.CD1, ...
                concVars_k.zFront10, concVars_k.zFront50, concVars_k.zFront90, concVars_k.zWidth, concVars_k.zWidthDiff, ...
                'VariableNames',{'timeStamp','timeElapsed','secondsElapsed','volInjected','tDtotal','CD1','zFront10','zFront50','zFront90','zWidth','zWidthDiff'});
            concBTlinesBefore = [concBTlinesBefore; concBTlinesBefore_temp];
            concBTcore = [concBTcore; concBTcore_temp];
            
        end

        rhoNormVars_temp = expCTData.(filedataExp.Key).exp.(run_name).rhoNormVars;
        rhoNormVars_tempTable = struct2table(rhoNormVars_temp,'AsArray',true);
        rhoNormVarsAll = [rhoNormVarsAll;rhoNormVars_tempTable];

        concVars_temp = expCTData.(filedataExp.Key).exp.(run_name).concVars;
        concVars_tempTable = struct2table(concVars_temp,'AsArray',true);
        concVarsAll = [concVarsAll;concVars_tempTable];

    end
    expCTData.(filedataExp.Key).BTlinesBefore.rhoNorm = rhoNormBTlinesBefore;
    expCTData.(filedataExp.Key).BTcore.rhoNorm = rhoNormBTcore;
    expCTData.(filedataExp.Key).VarsAll.rhoNorm = rhoNormVarsAll;

    expCTData.(filedataExp.Key).BTlinesBefore.conc = concBTlinesBefore;
    expCTData.(filedataExp.Key).BTcore.conc = concBTcore;
    expCTData.(filedataExp.Key).VarsAll.conc = concVarsAll;

    % save expCTData
    expCT_name = pathExportAll + filedataExp.Key;
    expCTDataSave = expCTData.(filedataExp.Key);
    save(expCT_name + '.mat','expCTDataSave','-v7.3')
end
